const TOUR_LABELS = {
    en: { next: 'Next', back: 'Back', skip: 'Skip', finish: 'Finish', step: 'Step' },
    es: { next: 'Siguiente', back: 'Atrás', skip: 'Omitir', finish: 'Terminar', step: 'Paso' }
};

let tourStep = 0;
let tourBuilt = false;

function tourLang() {
    return (typeof currentLang === 'function' && currentLang() === 'es') ? 'es' : 'en';
}

function tourLabels() {
    return TOUR_LABELS[tourLang()];
}

function tourPath() {
    return window.location.pathname;
}

function buildTour() {
    if (tourBuilt) return;
    tourBuilt = true;

    const overlay = document.createElement('div');
    overlay.id = 'tour-overlay';
    overlay.className = 'fixed inset-0 z-[9999] pointer-events-none hidden';
    overlay.innerHTML = `
        <div id="tour-spot" class="absolute pointer-events-none rounded-lg transition-all"
             style="outline: 2px solid #1a73e8; outline-offset: 2px; box-shadow: 0 0 0 9999px rgba(15, 15, 15, 0.6);"></div>
        <div id="tour-pop" class="absolute pointer-events-auto bg-white rounded-xl shadow-2xl border border-[#e8eaed] p-5 w-[320px] max-w-[calc(100vw-16px)]">
            <div class="flex items-center justify-between mb-2">
                <span id="tour-count" class="text-xs font-medium text-[#5f6368]"></span>
                <button id="tour-close" class="text-[#5f6368] hover:text-[#202124] leading-none" aria-label="Close">&times;</button>
            </div>
            <h3 id="tour-title" class="text-base font-semibold text-[#202124] mb-1"></h3>
            <p id="tour-body" class="text-sm text-[#5f6368] leading-relaxed"></p>
            <div class="flex items-center justify-between mt-4">
                <button id="tour-skip" class="text-sm text-[#5f6368] hover:text-[#202124]"></button>
                <div class="flex gap-2">
                    <button id="tour-back" class="px-3.5 py-2 rounded-lg border border-[#dadce0] text-[#1a73e8] text-sm font-medium hover:bg-[#f8f9fa]"></button>
                    <button id="tour-next" class="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-lg bg-[#1a73e8] text-white text-sm font-medium hover:bg-[#1765cc]"></button>
                </div>
            </div>
        </div>`;
    document.body.appendChild(overlay);

    document.getElementById('tour-close').addEventListener('click', closeTour);
    document.getElementById('tour-skip').addEventListener('click', closeTour);
    document.getElementById('tour-back').addEventListener('click', () => goToStep(tourStep - 1));
    document.getElementById('tour-next').addEventListener('click', () => goToStep(tourStep + 1));

    window.addEventListener('resize', () => { if (!document.getElementById('tour-overlay').classList.contains('hidden')) positionStep(); });
    window.addEventListener('scroll', () => { if (!document.getElementById('tour-overlay').classList.contains('hidden')) positionStep(); }, { passive: true });
}

function startTour() {
    buildTour();
    localStorage.setItem('tour_active', '1');
    localStorage.setItem('tour_step', '0');
    goToStep(0);
}

function openOnboarding() {
    startTour();
}

function goToStep(index) {
    if (index < 0 || index >= TOUR_STEPS.length) {
        closeTour();
        return;
    }
    tourStep = index;
    localStorage.setItem('tour_step', String(index));

    const step = TOUR_STEPS[index];
    if (tourPath() !== step.path) {
        window.location.href = step.path;
        return;
    }
    highlightStep(index);
}

function highlightStep(index) {
    const step = TOUR_STEPS[index];
    const el = document.querySelector(step.selector);

    if (!el || el.getBoundingClientRect().width === 0) {
        // Element missing or hidden on this screen → skip forward.
        if (index < TOUR_STEPS.length - 1) {
            goToStep(index + 1);
        } else {
            closeTour();
        }
        return;
    }

    document.getElementById('tour-overlay').classList.remove('hidden');
    renderContent(step, index);
    positionStep();
}

function renderContent(step, index) {
    const lang = tourLang();
    const labels = tourLabels();
    const isLast = index === TOUR_STEPS.length - 1;

    document.getElementById('tour-count').textContent = `${labels.step} ${index + 1} / ${TOUR_STEPS.length}`;
    document.getElementById('tour-title').textContent = step.title[lang];
    document.getElementById('tour-body').textContent = step.body[lang];
    document.getElementById('tour-skip').textContent = labels.skip;
    document.getElementById('tour-back').textContent = labels.back;
    document.getElementById('tour-back').style.visibility = index === 0 ? 'hidden' : 'visible';
    document.getElementById('tour-next').textContent = isLast ? labels.finish : labels.next;
}

function positionStep() {
    const step = TOUR_STEPS[tourStep];
    const el = document.querySelector(step.selector);
    if (!el) return;

    const r = el.getBoundingClientRect();
    const spot = document.getElementById('tour-spot');
    spot.style.top = `${r.top}px`;
    spot.style.left = `${r.left}px`;
    spot.style.width = `${r.width}px`;
    spot.style.height = `${r.height}px`;

    const pop = document.getElementById('tour-pop');
    const popWidth = pop.offsetWidth;
    const popHeight = pop.offsetHeight;
    const gap = 14;

    let top = r.bottom + gap;
    if (top + popHeight > window.innerHeight - 12) {
        top = r.top - popHeight - gap;
    }
    if (top < 12) top = 12;

    let left = r.left + r.width / 2 - popWidth / 2;
    left = Math.max(8, Math.min(left, window.innerWidth - popWidth - 8));

    pop.style.top = `${top}px`;
    pop.style.left = `${left}px`;
}

function closeTour() {
    localStorage.removeItem('tour_active');
    localStorage.removeItem('tour_step');
    const overlay = document.getElementById('tour-overlay');
    if (overlay) overlay.classList.add('hidden');
}

// Resume the tour after a cross-page navigation.
document.addEventListener('DOMContentLoaded', () => {
    if (localStorage.getItem('tour_active') === '1') {
        buildTour();
        const step = parseInt(localStorage.getItem('tour_step') || '0', 10);
        setTimeout(() => highlightStep(step), 350);
    }
});
